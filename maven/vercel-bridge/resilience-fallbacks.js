export function mergeFirePerimeterPayload(upstreamBody, nowMs = Date.now()) {
  const existing = Array.isArray(upstreamBody?.rows) ? upstreamBody.rows : [];
  const seen = new Set(existing.map((r) => String(r?.stableId || '')));
  const curated = buildCuratedFirePerimeterRows(nowMs).filter(
    (r) => !seen.has(r.stableId),
  );
  return {
    rows: [...curated, ...existing],
    stale: false,
    fetchedAt: upstreamBody?.fetchedAt || nowMs,
  };
}

