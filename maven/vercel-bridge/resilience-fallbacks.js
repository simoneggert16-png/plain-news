export function mergeInciwebIndexPayload(upstreamRows) {
  const existing = Array.isArray(upstreamRows) ? upstreamRows : [];
  const seen = new Set(existing.map((r) => String(r?.id || '')));
  const curated = CURATED_INCIWEB_PUBLICATIONS.filter(
    (item) => !seen.has(item.id),
  ).map((item) => ({
    id: item.id,
    irwin_id: item.irwinId,
    title: item.title,
    type: 'Wildfire',
    state: item.state,
    lat: item.lat,
    lng: item.lng,
    size: item.size,
    simulated: true,
  }));
  return [...curated, ...existing];
}

export function resolveInciwebPublicationFallback(id, nowMs = Date.now()) {
  const cleanId = String(id || '').trim();
  const match = CURATED_INCIWEB_PUBLICATIONS.find((item) => item.id === cleanId);
  if (!match) return null;
  const changedSec = Math.floor((nowMs - 2 * 3_600_000) / 1000);
  return {
    id: match.id,
    irwin_id: match.irwinId,
    title: match.title,
    type: 'Wildfire',
    state: match.state,
    lat: match.lat,
    lng: match.lng,
    size: match.size,
    simulated: true,
    percent_of_perimeter_contained: match.percentContained,
    changed: changedSec,
    incident_info: {
      overview: `<p>${match.overview}</p>`,
      current_situation: `<p>${match.currentSituation}</p>`,
    },
    links: [
      {
        title: 'Copernicus EFFIS / NIFC Active Fire Portal',
        url: 'https://effis.jrc.ec.europa.eu',
      },
    ],
  };
}



