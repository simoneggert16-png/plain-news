  if (CURATED_TLE_GROUPS[key]) {
    return `${CURATED_TLE_GROUPS[key].join('\n')}\n`;
  }
  if (key.includes('resource')) return `${CURATED_TLE_GROUPS.resource.join('\n')}\n`;
  if (key.includes('science')) return `${CURATED_TLE_GROUPS.science.join('\n')}\n`;
