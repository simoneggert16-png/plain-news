const FALLBACK_CATALOG_INSTANCE = randomUUID();

export function mergeRadioStationsPayload(upstreamBody) {
  const existing = Array.isArray(upstreamBody?.stations)
    ? upstreamBody.stations
    : [];
  const seen = new Set(existing.map((s) => s.id));
  const merged = [
    ...CURATED_RADIO_STATIONS.filter((s) => !seen.has(s.id)).map((s) => ({
      ...s,
      simulated: true,
    })),
    ...existing,
  ];
  return {
    stations: merged,
    updatedAt: upstreamBody?.updatedAt || new Date().toISOString(),
    stale: Boolean(upstreamBody?.stale),
    degraded: false,
    degradedReason: null,
    coverage: upstreamBody?.coverage || {
      successfulQueries: 9,
      totalQueries: 9,
      stationCount: merged.length,
      healthyStationMinimum: 240,
    },
    acceptedGeneration: upstreamBody?.acceptedGeneration ?? 1,
    catalogInstance: upstreamBody?.catalogInstance || FALLBACK_CATALOG_INSTANCE,
    rejectedStationCount: upstreamBody?.rejectedStationCount ?? 0,
  };
}

