export function buildKeylessFirmsPayload(nowMs = Date.now()) {
  const fires = CURATED_FIRMS_SEEDS.map((seed, index) => {
    const offsetMs = ((index * 17) % 660) * 60_000;
    const d = new Date(nowMs - offsetMs);
    const yyyy = d.getUTCFullYear();
    const mm = String(d.getUTCMonth() + 1).padStart(2, '0');
    const dd = String(d.getUTCDate()).padStart(2, '0');
    const hh = String(d.getUTCHours()).padStart(2, '0');
    const min = String(d.getUTCMinutes()).padStart(2, '0');
    return {
      lat: seed.lat,
      lon: seed.lon,
      brightness: seed.brightness,
      frp: seed.frp,
      confidence: seed.confidence,
      daynight: seed.daynight,
      acqDate: `${yyyy}-${mm}-${dd}`,
      acqTime: `${hh}${min}`,
      satellite: seed.sat,
      simulated: true,
    };
  });

  return {
    fetchedAt: nowMs,
    stale: false,
    simulated: true,
    ttlMs: FIRMS_TTL_MS,
    sources: [
      { source: 'VIIRS_NOAA20_NRT', count: 29, ok: true, simulated: true },
      { source: 'VIIRS_NOAA21_NRT', count: 19, ok: true, simulated: true },
      { source: 'VIIRS_SNPP_NRT', count: 12, ok: true, simulated: true },
      { source: 'MODIS_NRT', count: 0, ok: true, simulated: true },
    ],
    count: fires.length,
    fires,
  };
}

