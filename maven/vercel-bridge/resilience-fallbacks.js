  if (key.includes('weather')) return `${CURATED_TLE_GROUPS.weather.join('\n')}\n`;
  if (key === 'visual' || key.includes('military')) {
    return `${[...CURATED_TLE_GROUPS.visual, ...FALLBACK_TLE_MISSIONS].join('\n')}\n`;
  }
  if (key.includes('gps')) return `${CURATED_TLE_GROUPS['gps-ops'].join('\n')}\n`;
  if (key.includes('glo')) return `${CURATED_TLE_GROUPS['glo-ops'].join('\n')}\n`;
  if (key.includes('galileo')) return `${CURATED_TLE_GROUPS.galileo.join('\n')}\n`;
  if (key.includes('starlink')) return `${CURATED_TLE_GROUPS.starlink.join('\n')}\n`;
  if (key.includes('geo')) return `${CURATED_TLE_GROUPS.geo.join('\n')}\n`;
