export function mergeLaunchesPayload(upstreamBody, nowMs = Date.now()) {
  const existing = Array.isArray(upstreamBody?.results)
    ? upstreamBody.results
    : Array.isArray(upstreamBody)
      ? upstreamBody
      : [];
  const seen = new Set(existing.map((r) => String(r?.id || '')));
  const curated = buildCuratedLaunches(nowMs).filter((r) => !seen.has(r.id));
  const results = [...curated, ...existing];
  return {
    count: results.length,
    next: null,
    previous: null,
    results,
  };
}

