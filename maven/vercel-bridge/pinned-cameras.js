function hashCameraId(id) {
  const s = String(id || '');
  let h = 0;
  for (let i = 0; i < s.length; i += 1) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return h;
}

async function fetchImageUrlBytes(url, { bust = false, timeoutMs = 6000 } = {}) {
  if (!url || !/^https?:\/\//i.test(url)) return null;
  const target = bust
    ? `${url}${url.includes('?') ? '&' : '?'}gev=${Math.floor(Date.now() / 1000)}`
    : url;
  const response = await fetch(target, {
    headers: {
      Accept: 'image/jpeg,image/*',
      'User-Agent': 'gods-eye-view/1.0',
      ...(bust ? { 'Cache-Control': 'no-cache', Pragma: 'no-cache' } : {}),
    },
    signal: AbortSignal.timeout(timeoutMs),
  });
  if (!response.ok) return null;
  const type = response.headers.get('content-type') || 'image/jpeg';
  if (!type.startsWith('image/')) return null;
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length < 512 || bytes.length > MAX_BYTES) return null;
  const lastModified =
    Date.parse(response.headers.get('last-modified') || '') || 0;
  return {
    type,
    bytes,
    capturedAt: lastModified || Date.now(),
  };
}

export async function fetchGeoFallbackFrame(camera) {
  const lat = Number(camera?.lat);
  const lon = Number(camera?.lon);
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;

  // 1. Try camera's own backupUrl / backupUrls / ROUND_SHOT_BACKUP_URLS if configured
  const backupCandidates = [
    ...(Array.isArray(camera?.backupUrls) ? camera.backupUrls : []),
    ...(camera?.backupUrl ? [camera.backupUrl] : []),
    ...(ROUND_SHOT_BACKUP_URLS[camera?.id] || []),
  ];
  for (const candidateUrl of new Set(backupCandidates.filter(Boolean))) {
    try {
      const backup = await fetchImageUrlBytes(candidateUrl, { timeoutMs: 5000 });
      if (backup) return backup;
    } catch {
      /* continue */
    }
  }

  // 2. Fallback to nearest live outdoor webcam in Windy directory
  try {
    const cams = await windyWebcams();
    if (Array.isArray(cams) && cams.length > 0) {
      const scored = [];
      for (const item of cams) {
        const dLat = Number(item.lat) - lat;
        const dLon =
          (Number(item.lon) - lon) * Math.cos((lat * Math.PI) / 180);
        const distSq = dLat * dLat + dLon * dLon;
        scored.push({ item, distSq });
      }
      scored.sort((a, b) => a.distSq - b.distSq);
      const top = scored.slice(0, 6);
      const startIdx = hashCameraId(camera.id) % top.length;
      for (let k = 0; k < top.length; k += 1) {
        const candidate = top[(startIdx + k) % top.length].item;
        const frame = await windyCameraFrame(candidate, { bust: false });
        if (frame?.bytes?.length >= 1024) {
          return {
            type: frame.type,
            bytes: frame.bytes,
            capturedAt: candidate.updatedAt || Date.now() - 60_000,
          };
        }
      }
    }
  } catch {
    /* ignore */
  }

  // 3. Fallback to nearest verified live HD camera in CAMERAS (foto-webcam.eu / rheintalwetter.ch)
  try {
    const scoredPinned = [];
    for (const item of CAMERAS) {
      if (item.id === camera?.id || item.kind !== 'image' || !item.url) continue;
      const isIndependent = !item.url.includes('imgproxy.windy.com');
      const dLat = Number(item.lat) - lat;
      const dLon = (Number(item.lon) - lon) * Math.cos((lat * Math.PI) / 180);
      const distSq = dLat * dLat + dLon * dLon + (isIndependent ? 0 : 0.25);
      scoredPinned.push({ item, distSq });
    }
    scoredPinned.sort((a, b) => a.distSq - b.distSq);
    const topPinned = scoredPinned.slice(0, 5);
    for (const entry of topPinned) {
      const frame = await fetchImageUrlBytes(entry.item.url, { timeoutMs: 5000 }).catch(
        () => null,
      );
      if (frame?.bytes?.length >= 1024) {
        return frame;
      }
    }
  } catch {
    /* ignore */
  }

  return null;
}

async function fetchStreetViewFrame(camera) {
  return fetchGeoFallbackFrame(camera);
}

async function newestAvisecPicture(camera, { fresh = false } = {}) {
  const held = listCache.get(camera.id);
  if (!fresh && held && Date.now() - held.at < LIST_TTL_MS) return held;
  const response = await fetch(AVISEC_API + '/' + camera.feed, {
    headers: { Accept: 'application/json', 'User-Agent': 'gods-eye-view/1.0' },
    signal: AbortSignal.timeout(6000),
  });
  if (!response.ok) throw new Error(`feed HTTP ${response.status}`);
  const list = await response.json();
  const newest = Array.isArray(list) ? list[0] : null;
  const image = String(newest?.image || '');
  if (!/^https:\/\//.test(image)) throw new Error('feed has no picture');
  const entry = { at: Date.now(), image, time: Date.parse(newest?.time) || 0 };
  listCache.set(camera.id, entry);
  return entry;
}

/** When a plain still was published, without downloading it. */
async function stillLastModified(camera) {
  const held = headTimes.get(camera.id);
  if (held && Date.now() - held.at < HEAD_TTL_MS) return held.time;
  const response = await fetch(camera.url, {
    method: 'HEAD',
    headers: { Accept: 'image/*', 'User-Agent': 'gods-eye-view/1.0' },
    signal: AbortSignal.timeout(4000),
  });
  if (!response.ok) return 0;
  const time = Date.parse(response.headers.get('last-modified') || '') || 0;
  if (time) headTimes.set(camera.id, { at: Date.now(), time });
  return time;
}

