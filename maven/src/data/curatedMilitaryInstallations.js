export function enrichMilitaryNamesCatalog(names) {
  if (!names || !Array.isArray(names.records) || names.records.length < 1000) {
    return names;
  }
  if (names._curatedEnriched) return names;
  const mergedRecords = [...CURATED_MILITARY_INSTALLATIONS, ...names.records];
  mergedRecords.sort(
    (a, b) => b.areaM2 - a.areaM2 || a.osmKey.localeCompare(b.osmKey),
  );
  const byId = new Map(names.byId);
  for (const r of CURATED_MILITARY_INSTALLATIONS) {
    byId.set(r.osmKey, r);
  }
  return {
    records: mergedRecords,
    byId,
    _curatedEnriched: true,
  };
}

export function curatedInstallationsInBox(box, retrievedAt = new Date().toISOString()) {
  if (!box) return [];
  const width =
    box.east >= box.west ? box.east - box.west : 360 + box.east - box.west;
  return CURATED_MILITARY_INSTALLATIONS.filter((r) => {
    const x = (r.longitude - box.west + 360) % 360;
    return x <= width && r.latitude >= box.south && r.latitude <= box.north;
  }).map((r) => ({
    ...r,
    retrievedAt,
    sources: r.sources.map((s) => ({ ...s, retrievedAt })),
  }));
}
