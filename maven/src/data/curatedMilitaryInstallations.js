function boxAround(lon, lat, halfLon = 0.012, halfLat = 0.008) {
  return [
    Number((lon - halfLon).toFixed(5)),
    Number((lat - halfLat).toFixed(5)),
    Number((lon + halfLon).toFixed(5)),
    Number((lat + halfLat).toFixed(5)),
  ];
}

function footprintFromBbox([west, south, east, north]) {
  return [
    [
      [
        [west, south],
        [east, south],
        [east, north],
        [west, north],
        [west, south],
      ],
    ],
  ];
}

